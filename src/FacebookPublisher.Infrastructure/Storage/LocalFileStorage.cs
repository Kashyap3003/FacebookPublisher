using System.Security.Cryptography;
using FacebookPublisher.Application.Abstractions;
using FacebookPublisher.Application.Common;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;

namespace FacebookPublisher.Infrastructure.Storage;

public sealed class FileStorageOptions
{
    public const string SectionName = "Storage";

    /// <summary>Absolute path, or a path relative to the application's content root.</summary>
    public string RootPath { get; set; } = "App_Data/uploads";
}

/// <summary>
/// Stores uploads on local disk as {root}/{ownerId}/{random name}; original names are kept only in the database.
/// The owner folder comes from the user id (never from a file name), and stored names are validated so a request
/// can never reach outside its owner's folder. Files are not served directly: the media endpoint looks them up
/// through an owner-scoped query first.
/// </summary>
public sealed class LocalFileStorage : IFileStorage
{
    private readonly string _root;
    private readonly ILogger<LocalFileStorage> _logger;

    public LocalFileStorage(IOptions<FileStorageOptions> options, string contentRootPath, ILogger<LocalFileStorage> logger)
    {
        _root = Path.GetFullPath(Path.IsPathRooted(options.Value.RootPath)
            ? options.Value.RootPath
            : Path.Combine(contentRootPath, options.Value.RootPath));
        _logger = logger;
        Directory.CreateDirectory(_root);
    }

    public async Task<StoredFile> SaveAsync(Guid ownerId, Stream content, string originalFileName, long maxBytes, CancellationToken cancellationToken)
    {
        var extension = Path.GetExtension(originalFileName).ToLowerInvariant();
        var storedName = $"{Guid.NewGuid():N}{extension}";
        var path = GetFullPath(ownerId, storedName);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);

        using var sha = IncrementalHash.CreateHash(HashAlgorithmName.SHA256);
        long total = 0;
        try
        {
            await using (var output = new FileStream(path, FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, useAsync: true))
            {
                var buffer = new byte[81920];
                int read;
                while ((read = await content.ReadAsync(buffer, cancellationToken)) > 0)
                {
                    total += read;
                    if (total > maxBytes)
                    {
                        throw new AppValidationException($"'{originalFileName}' exceeds the maximum size of {maxBytes.ToFileSize()}.");
                    }
                    sha.AppendData(buffer, 0, read);
                    await output.WriteAsync(buffer.AsMemory(0, read), cancellationToken);
                }
            }

            if (total == 0)
            {
                throw new AppValidationException($"'{originalFileName}' is empty.");
            }
        }
        catch
        {
            TryDelete(path);
            throw;
        }

        _logger.LogInformation("Stored upload for user {OwnerId} as {StoredFileName} ({Size} bytes)", ownerId, storedName, total);
        return new StoredFile(storedName, total, Convert.ToHexString(sha.GetHashAndReset()));
    }

    public Stream OpenRead(Guid ownerId, string storedFileName) =>
        new FileStream(GetFullPath(ownerId, storedFileName), FileMode.Open, FileAccess.Read, FileShare.Read, 81920, useAsync: true);

    public string GetFullPath(Guid ownerId, string storedFileName) =>
        Path.Combine(OwnerFolder(ownerId), ValidateName(storedFileName));

    public bool Exists(Guid ownerId, string storedFileName) => File.Exists(GetFullPath(ownerId, storedFileName));

    public void Delete(Guid ownerId, string storedFileName) => TryDelete(GetFullPath(ownerId, storedFileName));

    /// <summary>
    /// One-time move of a file stored before multi-user support (directly in the root) into its owner's folder.
    /// Returns true when the file was moved.
    /// </summary>
    public bool MoveLegacyFile(Guid ownerId, string storedFileName)
    {
        var legacyPath = Path.Combine(_root, ValidateName(storedFileName));
        var ownerPath = GetFullPath(ownerId, storedFileName);
        if (!File.Exists(legacyPath) || File.Exists(ownerPath))
        {
            return false;
        }
        Directory.CreateDirectory(Path.GetDirectoryName(ownerPath)!);
        File.Move(legacyPath, ownerPath);
        return true;
    }

    private string OwnerFolder(Guid ownerId)
    {
        if (ownerId == Guid.Empty)
        {
            throw new ArgumentException("An owner id is required.", nameof(ownerId));
        }
        return Path.Combine(_root, ownerId.ToString("N"));
    }

    // Stored names are generated by this class; reject anything that could escape the owner folder.
    private static string ValidateName(string storedFileName)
    {
        if (string.IsNullOrWhiteSpace(storedFileName) || storedFileName != Path.GetFileName(storedFileName)
            || storedFileName.Contains("..", StringComparison.Ordinal))
        {
            throw new ArgumentException("Invalid stored file name.", nameof(storedFileName));
        }
        return storedFileName;
    }

    private void TryDelete(string path)
    {
        try
        {
            if (File.Exists(path))
            {
                File.Delete(path);
            }
        }
        catch (IOException ex)
        {
            _logger.LogWarning(ex, "Could not delete file {FileName}", Path.GetFileName(path));
        }
    }
}
